# Redis is the intended cache (Docker ships one). Locally, without a
# REDIS_URL and outside Docker, fall back to in-memory so `runserver` works
# out of the box. Token blacklist / sessions then live only per-process,
# which is fine for development.
_RUNNING_IN_DOCKER = Path("/.dockerenv").exists()

_redis_url = os.getenv("REDIS_URL", "")


def _redis_configured(url: str) -> bool:
    """True when Redis should be used.

    - Any explicit URL wins, unless it is the sentinel ``locmem`` which devs
      can set to run without a local Redis (``REDIS_URL=locmem``).
    - Inside Docker we default to the compose service even with no URL set.
    """
    if url.lower().startswith("locmem"):
        return False
    return bool(url) or _RUNNING_IN_DOCKER


